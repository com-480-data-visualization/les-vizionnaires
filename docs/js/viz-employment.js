/**
 * Module: Employment Connectivity Visualization
 * Description: Renders a D3.js bar chart displaying the average travel time
 * to IC hubs across all Swiss cantons to analyze employment distribution.
 * Dependency: d3.v7.min.js
 */

function renderEmploymentChart(containerId, dataUrl) {
  const container = document.getElementById(containerId);
  
  if (!container) {
    console.warn(`Container with ID '${containerId}' not found.`);
    return;
  }
  
  // Define chart dimensions and margins
  const margin = { top: 20, right: 20, bottom: 80, left: 70 };
  const chartWidth = 450 - margin.left - margin.right;
  const chartHeight = 350 - margin.top - margin.bottom;

  // Fetch JSON payload generated by the Python pipeline
  fetch(dataUrl)
    .then(response => {
      if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
      return response.json();
    })
    .then(data => {
      // Validate data payload
      if (!data.data || data.data.length === 0) {
        console.warn("No data available for Employment Chart.");
        return;
      }

      // ==========================================
      // BUG FIX: RACE CONDITION PREVENTION
      // We clear the container ONLY after the data is loaded and validated.
      // This prevents duplicate SVGs if the user clicks the tab multiple times rapidly.
      // ==========================================
      container.innerHTML = '';

      // Sort cantons by travel time (descending) for a cleaner bar distribution
      const cantonData = data.data.sort((a, b) => b.avg_travel_time - a.avg_travel_time);

      // Initialize SVG canvas
      const svg = d3.select(`#${containerId}`)
        .append('svg')
        .attr('width', chartWidth + margin.left + margin.right)
        .attr('height', chartHeight + margin.top + margin.bottom)
        .append('g')
        .attr('transform', `translate(${margin.left},${margin.top})`);

      // --- Scales ---
      // X-Axis: Cantons (Categorical Band Scale)
      const xScale = d3.scaleBand()
        .domain(cantonData.map(d => d.canton))
        .range([0, chartWidth])
        .padding(0.2);

      // Y-Axis: Average Travel Time (Linear Scale)
      const yScale = d3.scaleLinear()
        .domain([0, d3.max(cantonData, d => d.avg_travel_time)])
        .range([chartHeight, 0]);

      // --- Data Binding & Rendering (Bars) ---
      svg.selectAll('.bar')
        .data(cantonData)
        .enter()
        .append('rect')
        .attr('x', d => xScale(d.canton))
        .attr('y', d => yScale(d.avg_travel_time))
        .attr('width', xScale.bandwidth())
        .attr('height', d => chartHeight - yScale(d.avg_travel_time))
        .attr('fill', '#ff8c42') // Standard qualitative orange
        .attr('opacity', 0.8)
        .on('mouseover', function(event, d) {
          // Highlight active bar
          d3.select(this).attr('opacity', 1);

          // Create and position tooltip dynamically
          const tooltip = document.createElement('div');
          tooltip.className = 'tooltip';
          tooltip.innerHTML = `
            <strong>${d.canton}</strong><br/>
            Avg Travel: ${d.avg_travel_time.toFixed(1)} min
          `;
          document.body.appendChild(tooltip);
          
          // Offset tooltip slightly from cursor coordinates
          tooltip.style.left = `${event.pageX + 10}px`;
          tooltip.style.top = `${event.pageY + 10}px`;
        })
        .on('mouseout', function() {
          // Restore default bar styling
          d3.select(this).attr('opacity', 0.8);
          
          // Remove all active tooltips from the DOM
          document.querySelectorAll('.tooltip').forEach(t => t.remove());
        });

      // --- Axes Configuration ---
      // Build X-Axis
      svg.append('g')
        .attr('transform', `translate(0,${chartHeight})`)
        .call(d3.axisBottom(xScale))
        .attr('font-size', '11px')
        .selectAll('text')
        .attr('transform', 'rotate(45)')
        .style('text-anchor', 'start'); // Use style() instead of attr() for text-anchor

      svg.append('text')
        .attr('x', chartWidth / 2)
        .attr('y', chartHeight + 70)
        .attr('fill', '#475569')
        .style('text-anchor', 'middle')
        .style('font-size', '12px')
        .text('Canton');

      // Build Y-Axis
      svg.append('g')
        .call(d3.axisLeft(yScale).ticks(5))
        .attr('font-size', '12px');

      svg.append('text')
        .attr('transform', 'rotate(-90)')
        .attr('x', -chartHeight / 2)
        .attr('y', -55)
        .attr('fill', '#475569')
        .style('text-anchor', 'middle')
        .style('font-size', '12px')
        .text('Avg Travel Time (min)');

      // --- Footer Statistics Box ---
      const stats = document.createElement('div');
      stats.className = 'correlation-stats';
      stats.innerHTML = `
        <strong>Distribution:</strong> Uniform coverage<br/>
        <strong>Sample:</strong> ${cantonData.length} cantons analyzed
      `;
      container.appendChild(stats);
      
    })
    .catch(error => {
      console.error("Failed to render Employment Chart:", error);
    });
}