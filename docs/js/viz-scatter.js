/**
 * Module: Accessibility Paradox Visualization
 * Description: Renders a D3.js scatter plot correlating average travel time
 * to IC hubs against municipal real estate prices (CHF/m²).
 * Dependency: d3.v7.min.js
 */

function renderScatterPlot(containerId, dataUrl) {
  const container = document.getElementById(containerId);
  
  if (!container) {
    console.warn(`Container with ID '${containerId}' not found.`);
    return;
  }
  
  // Define chart dimensions and margins
  const margin = { top: 20, right: 20, bottom: 60, left: 70 };
  const width = Math.min(container.clientWidth - 30, 500) - margin.left - margin.right;
  const height = 380 - margin.top - margin.bottom;

  // Fetch JSON payload generated by the Python pipeline
  fetch(dataUrl)
    .then(response => {
      if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
      return response.json();
    })
    .then(data => {
      // Validate data payload
      if (!data.data || data.data.length === 0) {
        console.warn("No data available for Scatter Plot.");
        return;
      }

      // Filter out invalid or missing real estate prices to prevent D3 calculation errors
      const validData = data.data.filter(d => 
        d.Price_per_m2 != null && 
        !isNaN(d.Price_per_m2) && 
        d.Price_per_m2 > 0
      );

      if (validData.length === 0) {
        console.warn("No valid real estate data points found after filtering.");
        return;
      }

      // ==========================================
      // BUG FIX: RACE CONDITION PREVENTION
      // We clear the container ONLY after the data is loaded and validated.
      // ==========================================
      container.innerHTML = '';

      // Initialize SVG canvas
      const svg = d3.select(`#${containerId}`)
        .append('svg')
        .attr('width', width + margin.left + margin.right)
        .attr('height', height + margin.top + margin.bottom)
        .append('g')
        .attr('transform', `translate(${margin.left},${margin.top})`);

      // --- Scales ---
      // X-Axis: Average Travel Time (Linear)
      const xScale = d3.scaleLinear()
        .domain([0, d3.max(validData, d => d.avg_travel_time_ic)])
        .range([0, width]);

      // Y-Axis: Real Estate Price (Linear)
      const yScale = d3.scaleLinear()
        .domain([0, d3.max(validData, d => d.Price_per_m2)])
        .range([height, 0]);

      // --- Data Binding & Rendering (Scatter Points) ---
      svg.selectAll('.point')
        .data(validData)
        .enter()
        .append('circle')
        .attr('cx', d => xScale(d.avg_travel_time_ic))
        .attr('cy', d => yScale(d.Price_per_m2))
        .attr('r', 4)
        .attr('fill', '#1f77b4') // Standard qualitative blue
        .attr('opacity', 0.6)
        .on('mouseover', function(event, d) {
          // Highlight active point
          d3.select(this)
            .attr('r', 6)
            .attr('opacity', 1);

          // Create and position tooltip dynamically
          const tooltip = document.createElement('div');
          tooltip.className = 'tooltip';
          tooltip.innerHTML = `
            <strong>${d.name}</strong><br/>
            Travel: ${d.avg_travel_time_ic.toFixed(0)} min<br/>
            Price: CHF ${d.Price_per_m2.toFixed(0)}/m²
          `;
          document.body.appendChild(tooltip);
          
          // Offset tooltip slightly from cursor coordinates
          tooltip.style.left = `${event.pageX + 10}px`;
          tooltip.style.top = `${event.pageY + 10}px`;
        })
        .on('mouseout', function() {
          // Restore default point styling
          d3.select(this)
            .attr('r', 4)
            .attr('opacity', 0.6);
            
          // Remove all active tooltips from the DOM
          document.querySelectorAll('.tooltip').forEach(t => t.remove());
        });

      // --- Axes Configuration ---
      // Build X-Axis
      svg.append('g')
        .attr('transform', `translate(0,${height})`)
        .call(d3.axisBottom(xScale).ticks(5))
        .attr('font-size', '12px');
      
      svg.append('text')
        .attr('x', width / 2)
        .attr('y', height + 40)
        .attr('fill', '#475569')
        .style('text-anchor', 'middle')
        .style('font-size', '12px')
        .text('Travel Time to IC (minutes)');

      // Build Y-Axis
      svg.append('g')
        .call(d3.axisLeft(yScale).ticks(5))
        .attr('font-size', '12px');
      
      svg.append('text')
        .attr('transform', 'rotate(-90)')
        .attr('x', -height / 2)
        .attr('y', -55)
        .attr('fill', '#475569')
        .style('text-anchor', 'middle')
        .style('font-size', '12px')
        .text('Real Estate Price (CHF/m²)');

      // --- Footer Statistics Box ---
      const sampleCount = data.n_data || validData.length;
      const correlationVal = (data.correlation !== null && data.correlation !== undefined) 
        ? data.correlation.toFixed(3) 
        : 'N/A';

      const stats = document.createElement('div');
      stats.className = 'correlation-stats';
      stats.innerHTML = `
        <strong>Correlation:</strong> r = ${correlationVal}<br/>
        <strong>Sample:</strong> ${sampleCount} municipalities
      `;
      container.appendChild(stats);
      
    })
    .catch(error => {
      console.error("Failed to render Scatter Plot:", error);
    });
}