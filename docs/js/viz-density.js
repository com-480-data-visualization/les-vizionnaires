/**
 * Module: Density vs Isolation Visualization
 * Description: Renders an interactive D3.js scatter plot exploring the relationship
 * between population density and IC hub accessibility, filtered by canton.
 * Dependency: d3.v7.min.js
 */

function renderDensityChart(containerId, dataUrl) {
  const container = document.getElementById(containerId);
  
  if (!container) {
    console.warn(`Container with ID '${containerId}' not found.`);
    return;
  }
  
  // Chart layout configuration
  const margin = { top: 20, right: 15, bottom: 50, left: 60 };
  const chartWidth = 450 - margin.left - margin.right;
  const chartHeight = 350 - margin.top - margin.bottom;

  // Fetch JSON payload generated by the Python pipeline
  fetch(dataUrl)
    .then(response => {
      if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
      return response.json();
    })
    .then(data => {
      // Validate data presence
      if (!data.data || data.data.length === 0) {
        console.warn("No data available for Density Chart.");
        return;
      }

      // ==========================================
      // BUG FIX: RACE CONDITION PREVENTION
      // Clears container only after data is successfully retrieved.
      // ==========================================
      container.innerHTML = '';

      // Prepare UI elements
      const allCantons = Array.from(new Set(data.data.map(d => d.canton))).sort();
      
      // --- UI Setup: Canton Selector ---
      const selectorDiv = document.createElement('div');
      selectorDiv.className = 'canton-selector-container';
      selectorDiv.style.marginBottom = '20px';
      
      const label = document.createElement('label');
      label.style.fontWeight = '600';
      label.style.marginRight = '10px';
      label.textContent = 'Select Canton:';
      selectorDiv.appendChild(label);
      
      const select = document.createElement('select');
      select.id = 'canton-selector';
      Object.assign(select.style, {
        padding: '8px 12px',
        borderRadius: '4px',
        border: '1px solid #e2e8f0',
        fontSize: '14px',
        cursor: 'pointer'
      });
      
      allCantons.forEach(canton => {
        const option = document.createElement('option');
        option.value = canton;
        option.textContent = canton;
        select.appendChild(option);
      });
      
      selectorDiv.appendChild(select);
      container.appendChild(selectorDiv);
      
      // Container for the SVG chart
      const chartDiv = document.createElement('div');
      chartDiv.id = 'density-chart';
      container.appendChild(chartDiv);

      // Footer stats box for dynamic correlation display
      const statsBox = document.createElement('div');
      statsBox.className = 'correlation-stats';
      container.appendChild(statsBox);
      
      // Data grouping by canton for high-performance switching
      const cantonData = {};
      data.data.forEach(d => {
        if (!cantonData[d.canton]) cantonData[d.canton] = [];
        cantonData[d.canton].push(d);
      });

      // --- Rendering Function ---
      function renderCantonChart(canton) {
        const chartContainer = document.getElementById('density-chart');
        chartContainer.innerHTML = ''; 

        const cantonPoints = cantonData[canton] || [];
        if (cantonPoints.length === 0) return;

        // 1. Update dynamic statistics box with per-canton correlation
        let rText = 'N/A';
        let nText = cantonPoints.length;

        if (data.canton_stats && data.canton_stats[canton]) {
          const stats = data.canton_stats[canton];
          rText = (stats.r !== null) ? stats.r.toFixed(3) : 'N/A';
          nText = stats.n;
        }

        statsBox.innerHTML = `
          <strong>Canton:</strong> ${canton}<br/>
          <strong>Correlation:</strong> r = ${rText}<br/>
          <strong>Sample:</strong> ${nText} municipalities
        `;

        // 2. Render D3 Chart
        const svg = d3.select('#density-chart')
          .append('svg')
          .attr('width', chartWidth + margin.left + margin.right)
          .attr('height', chartHeight + margin.top + margin.bottom)
          .append('g')
          .attr('transform', `translate(${margin.left},${margin.top})`);

        const xScale = d3.scaleLinear()
          .domain([0, d3.max(cantonPoints, d => d.Pop_Density)])
          .range([0, chartWidth]);

        const yScale = d3.scaleLinear()
          .domain([0, d3.max(cantonPoints, d => d.avg_travel_time_ic)])
          .range([chartHeight, 0]);

        svg.selectAll('.point')
          .data(cantonPoints)
          .enter()
          .append('circle')
          .attr('cx', d => xScale(d.Pop_Density))
          .attr('cy', d => yScale(d.avg_travel_time_ic))
          .attr('r', 4)
          .attr('fill', '#9467bd')
          .attr('opacity', 0.6)
          .on('mouseover', function(event, d) {
            d3.select(this).attr('r', 6).attr('opacity', 1);
            const tooltip = document.createElement('div');
            tooltip.className = 'tooltip';
            tooltip.innerHTML = `
              <strong>${d.name}</strong><br/>
              Density: ${d.Pop_Density.toFixed(0)}/km²<br/>
              Travel: ${d.avg_travel_time_ic.toFixed(0)} min
            `;
            document.body.appendChild(tooltip);
            tooltip.style.left = `${event.pageX + 10}px`;
            tooltip.style.top = `${event.pageY + 10}px`;
          })
          .on('mouseout', function() {
            d3.select(this).attr('r', 4).attr('opacity', 0.6);
            document.querySelectorAll('.tooltip').forEach(t => t.remove());
          });

        // Axes and Labels
        svg.append('g')
          .attr('transform', `translate(0,${chartHeight})`)
          .call(d3.axisBottom(xScale).ticks(5))
          .attr('font-size', '12px');
        
        svg.append('text')
          .attr('x', chartWidth / 2)
          .attr('y', chartHeight + 40)
          .attr('fill', '#475569')
          .style('text-anchor', 'middle')
          .style('font-size', '12px')
          .text('Population Density (per km²)');

        svg.append('g')
          .call(d3.axisLeft(yScale).ticks(5))
          .attr('font-size', '12px');
        
        svg.append('text')
          .attr('transform', 'rotate(-90)')
          .attr('x', -chartHeight / 2)
          .attr('y', -45)
          .attr('fill', '#475569')
          .style('text-anchor', 'middle')
          .style('font-size', '12px')
          .text('Travel Time to IC (min)');
      }

      // Initialize with default canton
      renderCantonChart(allCantons[0]);

      // Update chart on selection change
      select.addEventListener('change', function() {
        renderCantonChart(this.value);
      });
    })
    .catch(error => {
      console.error("Failed to render Density Chart:", error);
    });
}